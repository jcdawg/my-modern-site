#!/usr/bin/env node
/**
 * Page date generator for www.thekasgroup.com
 *
 * Writes src/lib/page-dates.ts: a map of route path -> { published, modified }
 * taken from git history of each route's page.tsx:
 *   published = oldest author date   (git log --follow --format=%aI)
 *   modified  = newest author date
 *
 * Used by the sitemap (<lastmod>), Article JSON-LD (datePublished /
 * dateModified) and og:article times. Dates are committed so Vercel's shallow
 * clone does not matter at build time.
 *
 * Commits whose message contains "[skip-dates]" are ignored. Use that marker
 * for sitewide mechanical changes (schema wiring, metadata plumbing) so they
 * do not bump dateModified on every page. Content edits should NOT use it.
 *
 * Usage: node scripts/generate-page-dates.mjs   (or: npm run dates)
 */

import { execFileSync } from "node:child_process";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const APP_DIR = "src/app";
const OUT_FILE = "src/lib/page-dates.ts";

function findPages(dir) {
    const out = [];
    for (const name of readdirSync(dir)) {
        const full = join(dir, name);
        if (statSync(full).isDirectory()) out.push(...findPages(full));
        else if (name === "page.tsx") out.push(full);
    }
    return out;
}

function routeFor(file) {
    const rel = relative(APP_DIR, file).split(sep).slice(0, -1);
    // Drop route groups like (marketing)
    const parts = rel.filter((p) => !(p.startsWith("(") && p.endsWith(")")));
    return "/" + parts.join("/");
}

function gitDates(file) {
    const out = execFileSync(
        "git",
        ["log", "--follow", "--format=%aI", "--invert-grep", "--grep=\\[skip-dates\\]", "--", file],
        { encoding: "utf8" }
    ).trim();
    if (!out) return null;
    const lines = out.split("\n");
    return { published: lines[lines.length - 1], modified: lines[0] };
}

const entries = [];
for (const file of findPages(APP_DIR).sort()) {
    const dates = gitDates(file);
    if (!dates) continue; // not committed yet
    entries.push([routeFor(file), dates]);
}
entries.sort((a, b) => a[0].localeCompare(b[0]));

const body = entries
    .map(([route, d]) => `    ${JSON.stringify(route)}: { published: ${JSON.stringify(d.published)}, modified: ${JSON.stringify(d.modified)} },`)
    .join("\n");

const ts = `/**
 * AUTO-GENERATED by scripts/generate-page-dates.mjs. Do not edit by hand.
 * Real per-page dates from git history (oldest / newest commit touching each
 * route's page.tsx, excluding commits marked [skip-dates]).
 * Regenerate with: npm run dates
 */

export type PageDates = { published: string; modified: string };

export const PAGE_DATES: Record<string, PageDates> = {
${body}
};

export function getPageDates(path: string): PageDates | undefined {
    return PAGE_DATES[path];
}
`;

writeFileSync(OUT_FILE, ts);
console.log(`Wrote ${entries.length} routes to ${OUT_FILE}`);
